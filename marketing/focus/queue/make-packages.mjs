#!/usr/bin/env node
// Builds ready-to-post packages in queue/ for every rendered video (render/specs/*.json with an mp4 in videos/).
// One markdown file per video with Facebook Reel, TikTok and X sections, first comment and DM reply.
// Re-run after each new render:  node queue/make-packages.mjs
// {LANDING_URL} stays a placeholder until the owner hosts landing/index.html (owner-todo #4).
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const specs = readdirSync(join(ROOT, 'render/specs')).filter(f => f.endsWith('.json')).sort();
const DISC = 'Affiliate disclosure: some links on that page are affiliate links — I may earn a commission at no extra cost to you.';
const X_LIMIT = 280, URL_LEN = 23; // X counts every link as 23 chars

const rows = [];
for (const f of specs) {
  const spec = JSON.parse(readFileSync(join(ROOT, 'render/specs', f), 'utf8'));
  const mp4 = join(ROOT, 'videos', `${spec.out}.mp4`);
  if (!existsSync(mp4)) continue;
  const kw = spec.scenes.find(s => s.type === 'cta').keyword;
  const hook = spec.scenes.find(s => s.type === 'hook').text;
  const [body, tagLine] = spec.caption.split(/\n\n(?=#)/);
  const tags = (tagLine || '').trim().split(/\s+/).filter(Boolean);
  const mb = (statSync(mp4).size / 1e6).toFixed(2);

  // X: hook + CTA + up to 2 hashtags, must fit 280.
  let x = `${hook}\n\nComment ${kw} and I'll send the free guide.`;
  for (const t of tags.slice(0, 2)) if ((x + ' ' + t).length <= X_LIMIT) x += (x.endsWith('.') ? '\n\n' : ' ') + t;
  if (x.length > X_LIMIT) throw new Error(`X post too long for ${spec.out}: ${x.length}`);

  const fbFirst = `Comment ${kw} below and I'll DM you the free guide. Or grab it directly: {LANDING_URL}?k=${kw}\n${DISC}`;
  const dm = `Here you go 👉 {LANDING_URL}?k=${kw}\nIt opens straight to the checklist. (Some links on the page are affiliate links.)`;

  const md = `# Post package — ${spec.out}

- **Video:** \`videos/${spec.out}.mp4\` (1080x1920, ${mb} MB, silent — add a trending/royalty-free sound in-app)
- **Keyword:** \`${kw}\` → landing \`{LANDING_URL}?k=${kw}\`
- **Status:** ready, waiting on accounts (owner-todo #1) and landing URL (owner-todo #4)

## Facebook Reel
**Caption**
\`\`\`
${body.trim()}

${tags.join(' ')}
\`\`\`
**First comment (pin it)**
\`\`\`
${fbFirst}
\`\`\`

## TikTok
**Caption** (links in captions are not clickable for most accounts; rely on keyword → DM)
\`\`\`
${body.trim()} ${tags.slice(0, 5).join(' ')}
\`\`\`
**First comment**
\`\`\`
Comment ${kw} and I'll send it 👇
\`\`\`

## X
**Post** (${x.length}/280 chars, attach the mp4)
\`\`\`
${x}
\`\`\`
**Reply to own post** (link goes in the reply, not the main post)
\`\`\`
Free guide: {LANDING_URL}?k=${kw}
${DISC}
\`\`\`

## DM reply (all platforms, when someone comments ${kw})
\`\`\`
${dm}
\`\`\`
`;
  writeFileSync(join(ROOT, 'queue', `${spec.out}.md`), md);
  rows.push(`| ${spec.out} | ${kw} | ${mb} MB | ${x.length}/280 | ready |`);
}

const index = `# Post queue

Generated by \`node queue/make-packages.mjs\` from \`render/specs/\` + \`videos/\`. Do not hand-edit package files; edit the spec/script and regenerate.

Placeholder \`{LANDING_URL}\` = wherever the owner hosts \`landing/index.html\`. Until then, post with the keyword-only CTA (captions already work without a link).

| Package | Keyword | Video | X length | Status |
|---|---|---|---|---|
${rows.join('\n')}

## Suggested first week (one per day; order already alternates general / parent topics roughly)
${rows.map((r, i) => `${i + 1}. ${r.split('|')[1].trim()}`).join('\n')}

## Posting checklist (per video)
1. Upload the mp4; add a sound in-app at low volume (videos are silent).
2. Paste the caption for that platform.
3. Post the first comment / reply; pin it on Facebook.
4. Reply to keyword comments with the DM template (or set up an auto-DM tool once accounts exist).
5. After 48 h, note views / comments / keyword comments in \`marketing/focus/measure.md\` (no revenue figures in this public repo).
`;
writeFileSync(join(ROOT, 'queue', 'README.md'), index);
console.log(`wrote ${rows.length} packages`);
