// Regenerates the "Passed the gate" table in flywheel/DEMAND.md from data/offers.json,
// so the log always matches what is live. Run after adding or killing offers.
import fs from 'node:fs'
import path from 'node:path'
const root = path.resolve(new URL('.', import.meta.url).pathname, '../..')
const offers = JSON.parse(fs.readFileSync(path.join(root, 'data/offers.json'), 'utf8'))
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'flywheel/config.json'), 'utf8'))
const live = offers.filter(o => !['draft', 'killed'].includes(o.status) && o.demand)
const cell = s => String(s || '').replace(/\|/g, '/').replace(/\n/g, ' ')
const rows = live.map(o => {
  const d = o.demand
  const people = new Set(d.signals.map(s => s.who)).size
  const first = d.signals[0]
  return `| [${cell(o.name)}](${cfg.publicBase}/${o.slug}/) | ${cell(o.price)} | ${cell(o.buyer)} | ${cell(d.summary)} | ${cell(d.wtp)} | ${people} sources, e.g. [${cell(first.who)}](${first.url}) |`
})
const table = `<!-- passed:start (generated by scripts/flywheel/demand-log.mjs; edit data/offers.json instead) -->\n${live.length} live offers. Full evidence, with every quote and link, is in each offer's \`demand\` block in \`data/offers.json\`.\n\n| Offer | Price | Buyer | Demand | Money already spent | Evidence |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n<!-- passed:end -->`
const file = path.join(root, 'flywheel/DEMAND.md')
let s = fs.readFileSync(file, 'utf8')
if (s.includes('<!-- passed:start')) s = s.replace(/<!-- passed:start[\s\S]*?<!-- passed:end -->/, table)
else {
  const a = s.indexOf('## Passed the gate'), b = s.indexOf('## Candidates still short of evidence')
  s = s.slice(0, a) + '## Passed the gate\n\n' + table + '\n\n' + s.slice(b)
}
fs.writeFileSync(file, s)
console.log(`demand log: ${live.length} live offers`)
