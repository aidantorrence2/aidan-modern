package com.aidantorrence.syncstudy

val OUTLIERS_STUDY = study("outliers") {
    keyIdeas(
        "Success is never purely the product of individual talent and effort; outliers are shaped by hidden advantages, opportunities and cultural legacies.",
        "Small, arbitrary advantages, like being born just after an age cutoff, compound over time into large real differences, a process called accumulative advantage.",
        "Mastery takes roughly ten thousand hours of practice, and the chance to practice that much depends on luck, family and timing.",
        "The moment in history when you are born can open or close the door to extraordinary opportunities.",
        "Beyond a threshold, IQ matters less than practical intelligence, which is largely taught by family and social class.",
        "Cultural legacies, from cultures of honor to deference to authority to the rice farmer's persistence, shape behavior generations later and can be changed once recognized.",
        "The achievement gap between rich and poor children grows mainly during summer vacation, so more learning time can close it.",
        "Effort only pays off where opportunity exists, so society should build structures that create outliers rather than wait for geniuses.",
    )
    section(0) { // Look around, not just at
        card(
            "What is Gladwell's central thesis in Outliers?",
            "Success is not simply the product of individual talent and effort. Outliers are shaped by hidden advantages, well-timed opportunities and inherited cultural legacies, so to understand them you must look at their surroundings, not just at them.",
        )
        card(
            "What explained the low rate of heart disease in Roseto, Pennsylvania?",
            "Not diet, exercise, genes or location, which researchers ruled out, but the town's social fabric: extended families, shared meals, church and civic life, and an egalitarian culture that discouraged showing off and buffered people from stress.",
        )
        card(
            "Why does Gladwell open a book about success with a story about health?",
            "Roseto shows that an outcome we assume is individual can be produced by community and culture. Just as medicine had to look beyond the individual body, Gladwell argues we must look beyond individual traits to explain success.",
        )
        card(
            "Why does it matter practically whether success comes from circumstances rather than personal gifts alone?",
            "If success depended only on innate gifts, all we could do is find the gifted. Because it depends heavily on circumstances, those circumstances can be redesigned so that many more people get the chance to succeed.",
        )
    }
    section(1) { // The birthday advantage
        card(
            "What is accumulative advantage?",
            "A process in which a small, often arbitrary, initial edge earns someone extra opportunities, which produce real improvement that earns still more opportunities, so the original difference compounds into a large gap. It is also called the Matthew effect.",
        )
        card(
            "Why are elite Canadian hockey players disproportionately born early in the year?",
            "The age cutoff is January first, so children born just after it are up to a year older than their peers. Their greater maturity gets them picked for better teams with more coaching and more games, which turns a size advantage into genuine skill.",
        )
        card(
            "How does the birth-month effect show up in schools?",
            "The oldest children in a grade tend to score higher, are more often identified as gifted and placed in advanced tracks, and are more likely to attend university, because early sorting mistakes maturity for ability and then gives those children more.",
        )
        card(
            "Why does Gladwell say systems like youth hockey confuse opportunity with talent?",
            "They select children early based on maturity, give the chosen ones better development, and then point to their later superiority as evidence of natural talent, when the system itself manufactured much of the difference.",
        )
        card(
            "What remedies does Gladwell suggest for birth-month bias?",
            "Organize youth leagues or school groupings so children compete with others born in the same part of the year, and avoid early, irreversible sorting, so that late-born children are not quietly shut out of opportunities.",
        )
    }
    section(2) { // 10,000 hours
        card(
            "What does the ten thousand hour rule claim, and what is its deeper lesson?",
            "Research suggested that world-class performance in complex fields takes roughly ten thousand hours of practice. The deeper lesson is that mastery requires enormous practice, and the chance to practice that much depends on opportunities few people can create for themselves.",
        )
        card(
            "How do Bill Gates and the Beatles illustrate the ten thousand hour rule?",
            "Both got unusual chances to practice. Gates had access to a time-sharing computer terminal as a teenager when almost no one did, and the Beatles played marathon nightly sets in Hamburg. By the time they became famous, they had already logged an extraordinary amount of practice.",
        )
        card(
            "Why does Gladwell argue that the year you were born can shape your success?",
            "Major economic transformations open narrow windows. People born at the right time, like Americans in the 1830s for the industrial boom or programmers around 1955 for the personal computer, were ready when opportunity arrived and not yet locked into older paths.",
        )
        card(
            "How did Joe Flom's disadvantages become advantages?",
            "Shut out of elite law firms because he was Jewish and poor, he took the takeover and proxy work they disdained, which boomed decades later. Being born in a low-birth-rate generation also gave him smaller classes and more job opportunities.",
        )
        card(
            "What is the main criticism of the ten thousand hour rule?",
            "Critics, including the researcher whose work it drew on, argued that ten thousand is an average rather than a magic threshold, and that the quality of focused, deliberate practice matters as much as the number of hours.",
        )
    }
    section(3) { // Smart enough, then what?
        card(
            "What does Gladwell mean by saying intelligence has a threshold?",
            "Beyond a certain level, roughly enough to handle demanding work, extra IQ points add little to real-world success. Like height in basketball, you need enough, but past that point qualities such as creativity and practical intelligence matter more.",
        )
        card(
            "What is practical intelligence, and where does it come from?",
            "The social know-how of what to say to whom, when and how, so you can get what you need from people and institutions. Unlike IQ, it is largely learned, and Gladwell argues it is taught by family and social class.",
        )
        card(
            "How does concerted cultivation differ from natural growth?",
            "Middle-class parents cultivate children deliberately, organizing activities and teaching them to reason, question adults and negotiate. Working-class parents more often let children grow on their own, which builds independence but teaches deference to authority, leaving children less able to make institutions work for them.",
        )
        card(
            "Why did Chris Langan struggle while Robert Oppenheimer thrived?",
            "Both were brilliant, but Oppenheimer's privileged upbringing taught him to negotiate with authority, even talking his way out of serious trouble, while Langan, raised in poverty and chaos, could not get institutions to bend and dropped out of college.",
        )
        card(
            "What did Terman's study of gifted children ultimately reveal?",
            "A very high IQ did not guarantee great achievement. Among his subjects, the most and least successful had similar IQs, and what distinguished them was family background, showing that class mattered more than raw intelligence.",
        )
    }
    section(4) { // Cultural legacy
        card(
            "What is a cultural legacy, and why does it matter for success?",
            "Attitudes and habits inherited from ancestors that persist long after the conditions that created them. They shape how people respond to insults, authority and hard work, so explaining success or failure requires knowing where people come from.",
        )
        card(
            "How did deference to authority contribute to plane crashes, and how was it fixed?",
            "In high power distance cultures, junior officers hinted at dangers instead of directly challenging the captain, so small errors went uncorrected. Korean Air fixed its record by retraining crews to speak directly, using English to make the cockpit less hierarchical.",
        )
        card(
            "Why does Gladwell link rice farming to strength in mathematics?",
            "Rice paddy farming demanded relentless, careful work where extra effort visibly paid off, creating a culture that prizes persistence. Because maths success depends largely on persistence, that inherited attitude helps, along with East Asian number words that are simpler to learn.",
        )
        card(
            "What does the summer learning research reveal about the achievement gap?",
            "During the school year poor and wealthy children learn at similar rates, but in summer wealthier children keep learning while poorer ones stall. Over years, summer vacation accounts for most of the gap, which is why programs like KIPP add school time.",
        )
        card(
            "What is a culture of honor and where does it come from?",
            "A culture in which men must answer insults with force to protect their reputation, typical of herding peoples whose wealth could easily be stolen. Gladwell argues it explains Appalachian feuds and still affects how southerners react to insults today.",
        )
    }
    section(5) { // Build the ladders
        card(
            "What is Gladwell's final conclusion about effort and opportunity?",
            "Effort and talent matter, but they can only pay off where opportunity exists. Success follows from a predictable web of advantages, so instead of waiting for geniuses, society should build structures that extend those opportunities to more people.",
        )
        card(
            "How does Gladwell's mother's story illustrate the book's argument?",
            "Her journey from rural Jamaica to university in England depended on advantages she did not earn, such as her family's place in the color hierarchy, scholarships created after colonial unrest, a determined mother and a timely loan, combined with her own hard work.",
        )
        card(
            "What is meaningful work, and why does Gladwell think it matters?",
            "Work that is autonomous, complex and connects effort to reward. Families who do such work, like the immigrant garment workers of New York, teach their children that effort pays off, an inherited lesson that helps the next generation succeed.",
        )
        card(
            "Why does Gladwell see the myth of the self-made individual as harmful?",
            "By crediting success only to individuals, we ignore the arbitrary rules and circumstances that filter out capable people, from age cutoffs to summer vacations, so we fail to fix them and waste human potential.",
        )
        card(
            "What kinds of changes does Gladwell suggest would create more outliers?",
            "Fairer age groupings in sports and schools, more learning time for poor children as KIPP provides, workplace and cockpit cultures that encourage speaking up, and broader access to the resources that allow years of practice.",
        )
    }
}
