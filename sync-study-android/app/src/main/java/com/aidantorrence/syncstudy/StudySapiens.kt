package com.aidantorrence.syncstudy

val SAPIENS_STUDY = study("sapiens") {
    keyIdeas(
        "Homo sapiens came to dominate the planet not through physical strength but through a unique ability to cooperate flexibly in very large numbers.",
        "That cooperation rests on shared fictions, imagined orders such as gods, nations, money, laws and corporations, which exist only because many people believe in them.",
        "The Agricultural Revolution increased food and population but made most individual lives harder, a trap in which wheat in effect domesticated humans.",
        "Farming surpluses created elites, states, writing and hierarchies, all sustained by myths that people experience as natural truths.",
        "History has moved toward unity, driven by money, empires and universal religions, forces that were neither purely good nor purely evil.",
        "The Scientific Revolution began by admitting ignorance, and its feedback loop with empire and capitalism, built on credit and faith in growth, gave humanity unprecedented power.",
        "Industrial society replaced the family and community with the state and the market, bringing abundance and relative peace but not clearly more happiness, since expectations rise with every gain.",
        "Sapiens is now starting to replace natural selection with intelligent design, so the crucial question is no longer what we can do but what we will want to become.",
    )
    section(0) { // Three revolutions
        card(
            "What is the central question of Sapiens, and how does Harari answer it in outline?",
            "How did an insignificant ape come to rule the planet? Through three revolutions: a cognitive one that gave us language and shared fictions, an agricultural one that settled us and multiplied our numbers, and a scientific one that turned admitted ignorance into enormous power.",
        )
        card(
            "Why does Harari emphasize that sapiens were once one of several human species?",
            "Because our sense of being uniquely human is an illusion created by the disappearance of relatives like Neanderthals and Homo erectus. The fact that they vanished wherever sapiens arrived suggests sapiens had a new advantage, which Harari locates in the mind rather than the body.",
        )
        card(
            "Why does Harari distinguish biology from history?",
            "Biology sets the limits of what sapiens can do, but within those limits culture, shaped by shared stories, drives change. Since the Cognitive Revolution, history rather than genetic evolution has been the main way human behavior and societies change.",
        )
        card(
            "Why does Harari think our sudden rise to the top of the food chain still matters?",
            "Humans spent most of their history in the middle of the food chain and jumped to the top so quickly that neither we nor ecosystems had time to adjust. This leaves a species anxious about its position and therefore unusually cruel and dangerous.",
        )
        card(
            "What did the human body's distinctive features cost, and what did they not provide?",
            "Large brains consume huge amounts of energy, and upright walking strains the back and narrows the birth canal, so babies are born helpless and need a group to raise them. These traits made humans social and clever but did not make them dominant.",
        )
    }
    section(1) { // Shared stories
        card(
            "According to Harari, what is the truly unique power of human language?",
            "Not merely sharing information or gossip, but the ability to invent and discuss things that do not exist, such as gods, nations, laws and money. When many people believe the same fiction, it becomes a foundation for cooperation among strangers.",
        )
        card(
            "Why can humans cooperate in vast numbers while chimpanzees cannot?",
            "Chimpanzee cooperation depends on personal familiarity, so groups stay small. Humans can trust strangers who believe the same myths, so millions can work together flexibly, unlike ants and bees whose large-scale cooperation is rigid and genetically fixed.",
        )
        card(
            "What does the example of a limited liability company like Peugeot show?",
            "That some of the most powerful entities in the world are legal fictions. A company is not its factories, staff or products; it exists because people share belief in corporate law, yet it can own property, borrow, be sued and outlive its founders.",
        )
        card(
            "What is an imagined order, and why is it not simply a lie?",
            "It is a story that exists in the shared imagination of many people, like money, nations or human rights. Unlike a lie, nearly everyone believes it, and that shared belief gives it real power to organize behavior.",
        )
        card(
            "How did shared stories let sapiens change faster than any other species?",
            "Because social behavior came to rest on beliefs rather than genes, people could reshape society within a generation by changing the story, as the French Revolution did with kingship. Cultural change replaced slow biological evolution.",
        )
        card(
            "What was the ecological impact of early foragers?",
            "Wherever sapiens arrived, starting with Australia and then the Americas, most large animals soon disappeared. Long before farming or industry, hunting and burning by foragers made sapiens one of the most destructive species in the planet's history.",
        )
    }
    section(2) { // The wheat bargain
        card(
            "Why does Harari call the Agricultural Revolution history's biggest fraud?",
            "Because it produced more food per acre and a population boom, but individual farmers worked harder, ate a poorer diet, suffered more disease and famine, and lived under elites. It was a triumph for the species but often a worse life for the individual.",
        )
        card(
            "What does Harari mean by saying wheat domesticated humans?",
            "From wheat's point of view, it spread from a small patch of the Middle East to much of the globe by getting humans to clear land, water, weed and protect it, while humans became bound to fields and permanent houses.",
        )
        card(
            "What is the luxury trap, and how did it lock humans into farming?",
            "Each small step toward farming seemed sensible, but extra food led to more children, and the larger population could not return to foraging. Seeking an easier life, people built a harder one, a pattern repeated by modern time-saving technologies.",
        )
        card(
            "How did farming surpluses lead to elites, states and writing?",
            "Stored grain could be taken from peasants to feed priests, soldiers, kings and officials who did not farm. Running large societies required tracking taxes and property, so writing and bureaucracy were invented to manage information beyond human memory.",
        )
        card(
            "What does comparing the Code of Hammurabi with the Declaration of Independence reveal?",
            "Both are imagined orders that believers saw as natural truths, one claiming divine hierarchy and the other universal equality. Biologically neither is objective; they work because millions believe them and because belief is built into institutions and desires.",
        )
        card(
            "How do social hierarchies sustain themselves, according to Harari?",
            "They usually begin in historical accident and then persist through vicious circles: a group denied wealth and education becomes poor, and its poverty is taken as proof of inferiority, reinforcing the myth that justified excluding it.",
        )
    }
    section(3) { // What unites us
        card(
            "What is the overall direction of history according to Harari, and what drove it?",
            "Toward unity: countless separate cultures merged into one global civilization. Three universal orders drove this, money, empires and universal religions, each imagining all of humanity as one potential community of traders, subjects or believers.",
        )
        card(
            "Why does Harari call money a system of mutual trust?",
            "Money has value only because people believe others will accept it. That shared belief lets strangers with different languages, gods and rulers cooperate, even enemies in holy wars. But by making everything exchangeable, money can also corrode community and intimate values.",
        )
        card(
            "How does Harari evaluate empires?",
            "They were brutal and exploitative, yet they were also the main way small cultures merged into larger ones, spreading languages, laws and ideas. Most modern cultures are imperial legacies, so rejecting empire wholesale would mean rejecting much of what people now see as their own.",
        )
        card(
            "How did religion shift from local to universal, and why did that matter?",
            "Animism and polytheism were local and fairly tolerant, while monotheism and other universal faiths claimed one truth for all people and spread through missionaries and conquest. That universality helped unify vast populations but also fueled intolerance and religious war.",
        )
        card(
            "Why does Harari count liberalism, communism and nationalism as religions?",
            "He defines religion as a system of norms and values based on belief in a superhuman order. Modern ideologies, including humanism, rest on faith in natural laws or sacred human qualities, much as traditional religions rest on gods.",
        )
        card(
            "Why does Harari say history cannot be predicted and does not necessarily serve human good?",
            "History is a chaotic system that reacts to predictions about it, and outcomes seem inevitable only in hindsight. Cultures spread whether or not they benefit people, so history shows us alternatives rather than a guaranteed path of progress.",
        )
    }
    section(4) { // Admitting ignorance
        card(
            "What made the Scientific Revolution different from earlier knowledge traditions?",
            "Earlier traditions assumed everything important was already known through scripture or ancient sages. Modern science began by admitting ignorance, then used observation and mathematics to build theories and used those theories to gain new powers and technologies.",
        )
        card(
            "What is the feedback loop between science, empire and capitalism?",
            "Governments and investors funded research and exploration because they expected power and profit; the resulting knowledge produced more power and wealth, which funded still more research. This loop, more than any early technological lead, explains Europe's global dominance.",
        )
        card(
            "Why does credit depend on belief in a better future?",
            "A loan only makes sense if the economy will grow so the borrower can repay with interest. Once science made people believe in progress, they extended credit, which financed growth, which justified more trust, creating the modern growing economy.",
        )
        card(
            "Why does Harari link European imperialism to the scientific mindset?",
            "European conquerors, like scientists, assumed there were unknown lands and knowledge worth seizing and set out to find them. Other civilizations with comparable technology lacked that drive, and European expeditions routinely combined scientific study with conquest.",
        )
        card(
            "What was Adam Smith's revolutionary idea, as Harari presents it?",
            "That private self-interest can serve the public good: when people seek profit and reinvest it, they create jobs and wealth for others. This turned profit-seeking into a virtue and made reinvesting profits the core rule of capitalism.",
        )
        card(
            "What does Harari see as capitalism's dark side?",
            "Profit-driven companies ran the Atlantic slave trade, Britain fought wars to keep selling opium to China, and colonies were ruled ruthlessly for shareholders. Faith in growth and free markets is no guarantee of justice.",
        )
    }
    section(5) { // Power, but happiness?
        card(
            "Why does Harari doubt that our enormous gains in power have made us happier?",
            "Happiness depends largely on the gap between conditions and expectations, and expectations rise with every improvement. Brain chemistry also pulls us back to a familiar range of contentment, so material progress has produced far less happiness than power.",
        )
        card(
            "What future does Harari foresee for sapiens?",
            "Intelligent design through genetic engineering, cyborg technology and possibly non-organic life may replace natural selection, so sapiens could be transformed into very different beings. Our power to remake ourselves is outpacing our wisdom about what we should want.",
        )
        card(
            "How did the state and the market replace the family and local community?",
            "Industrial society offered education, care, work and security through governments and markets, on condition that people become individuals. This freed many from controlling families but left them dependent on impersonal institutions and belonging to imagined communities like nations and consumer tribes.",
        )
        card(
            "What was the essence of the Industrial Revolution according to Harari?",
            "A revolution in energy conversion: steam engines, then oil and electricity, unlocked energy far beyond muscle power and created abundance. The new challenge became demand, which was met by consumerism, an ethic that makes buying things a virtue.",
        )
        card(
            "What competing explanations of happiness does Harari weigh?",
            "Psychological views stress expectations and relationships, biological views say brain chemistry sets our range of happiness, and others argue happiness comes from seeing life as meaningful. Buddhism goes further, saying lasting peace comes from ceasing to crave pleasant feelings.",
        )
        card(
            "Why does Harari consider the modern era unusually peaceful?",
            "Nuclear weapons made war between great powers suicidal, wealth now comes from knowledge that cannot simply be seized, war has become less profitable, and global elites value peace. Violence persists, but the share of people dying in war has fallen.",
        )
    }
}
